/**
 * Splits `server/index.cjs` into:
 *
 *   server/report-core.cjs  — pure logic + HTML rendering (no fs / http / os)
 *                              shared by the local Node server and the
 *                              Cloudflare Worker.
 *   server/index.cjs         — the Node server: file storage + HTTP routing.
 *
 * Run it once after changing the boundaries:
 *   node scripts/split-server-core.cjs
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const serverPath = path.join(root, 'server', 'index.cjs');
const corePath = path.join(root, 'server', 'report-core.cjs');

const source = fs.readFileSync(serverPath, 'utf8');
const lines = source.split(/\r?\n/);

const slice = (from, to) => lines.slice(from - 1, to).join('\n');

// --- the ranges that are pure (no file system, no HTTP) --------------------
const PURE_RANGES = [
  [43, 61],    // esc, money, safeId
  [124, 185],  // emptySnapshot, snapshotOps
  [235, 907]   // dataOf … renderMonthlyPage
];

const coreHeader = `/**
 * Pharmacy POS — Report Core
 * ----------------------------
 * Pure, runtime-agnostic report logic: store helpers, aggregations and the
 * full Arabic (RTL) HTML templates.
 *
 * No file system, no HTTP, no Node-only API — so the very same code runs in:
 *   • the local Node report server  (server/index.cjs)
 *   • the Cloudflare Worker         (worker/src/index.js, KV instead of disk)
 *
 * Never edit this file by hand: it is generated by
 *   node scripts/split-server-core.cjs
 */
'use strict';

`;

const coreFooter = `
module.exports = {
  esc,
  money,
  safeId,
  emptySnapshot,
  snapshotOps,
  dataOf,
  buildShift,
  allShiftIds,
  dateKey,
  monthKey,
  normShift,
  normInvoice,
  normPurchase,
  normExpense,
  normReturn,
  collectRows,
  aggregateRange,
  buildDaily,
  buildMonthly,
  pageShell,
  renderShiftPage,
  renderIndex,
  renderDailyPage,
  renderMonthlyPage
};
`;

fs.writeFileSync(corePath, coreHeader + PURE_RANGES.map(([a, b]) => slice(a, b)).join('\n\n') + coreFooter, 'utf8');

console.log(`✅ report-core.cjs written (${PURE_RANGES.length} blocks)`);
